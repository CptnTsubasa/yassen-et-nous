import { chromium, LAUNCH } from '../lib/pw.mjs';
const b = await chromium.launch(LAUNCH);
const errs = [], W = ms => new Promise(r => setTimeout(r, ms)), ok = (n, v) => console.log((v ? 'OK  ' : 'FAIL') + ' ' + n);
const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
await ctx.route(/fonts\.(googleapis|gstatic)/, r => r.abort());
const p = await ctx.newPage(); p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:8123/?local'); await W(1200);
await p.evaluate(() => { Store.meta.couple = { a: 'Yanis', b: 'Sarah', style: 'partage' }; S.layer = null; S.obShown = true; render(true); }); await W(300);
await p.click('[data-a="tab"][data-tab="lettres"]'); await W(50);
ok('onglet vers la droite : glisse depuis la droite', await p.evaluate(() => document.querySelector('main.wrap').classList.contains('from-r')));
await p.click('[data-a="tab"][data-tab="home"]'); await W(50);
ok('retour vers la gauche : glisse depuis la gauche', await p.evaluate(() => document.querySelector('main.wrap').classList.contains('from-l')));
await p.click('[data-a="sheet"][data-name="names"]'); await W(50);
ok('fenêtre ouverte avec animation', await p.evaluate(() => document.querySelector('#layer .layer.in') !== null));
await p.evaluate(() => { ACT['close-layer'](); render(true); }); await W(60);
const mid = await p.evaluate(() => !!document.querySelector('#layer .layer.out'));
await W(400);
ok('fermeture en douceur, puis la fenêtre disparaît', mid && await p.evaluate(() => document.getElementById('layer').innerHTML === ''));
await p.evaluate(() => gainToast('Quête accomplie : +15 cœurs')); await W(300);
ok('les cœurs s\'envolent vers le compteur', (await p.$$('.fly-heart')).length === 7);
await p.screenshot({ path: 'anim-hearts.png' });
await W(1500);
ok('puis disparaissent, et le compteur bondit', (await p.$$('.fly-heart')).length === 0 && await p.evaluate(() => document.querySelector('.hearts-pill').classList.contains('pop')));
console.log('errors', JSON.stringify(errs)); await b.close();
